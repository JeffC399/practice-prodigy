#!/usr/bin/env node
/**
 * generate-methodology-content — Slice E.1 (Phase 135).
 *
 * Reads every .md file in src/content/methodology and every .json in
 * src/content/templates, then writes src/lib/practice/methodology-
 * content.generated.ts with the loaded content baked in as ESM
 * exports:
 *
 *   METHODOLOGY_ARTICLES: MethodologyArticle[]
 *   METHODOLOGY_TEMPLATES: MethodologyTemplate[]
 *
 * Rationale: bundling markdown as raw strings via Turbopack loaders
 * needs external deps and a config change. This one-shot generator
 * keeps the bundle lean, requires zero deps, and only needs to be
 * re-run when the content files change (rare). Run it any time via
 * `node scripts/generate-methodology-content.mjs`.
 *
 * The generator DOES parse the YAML frontmatter (minimal — key/value
 * + list-with-brackets) into a typed object so the article's
 * metadata (id, name, summary, categories, templates) is available
 * at runtime without a runtime YAML parser.
 */

import { readFileSync, writeFileSync, readdirSync } from "node:fs";
import { join, dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = resolve(__dirname, "..");
const METHODOLOGY_DIR = join(REPO_ROOT, "src/content/methodology");
const TEMPLATES_DIR = join(REPO_ROOT, "src/content/templates");
const OUT_FILE = join(
  REPO_ROOT,
  "src/lib/practice/methodology-content.generated.ts",
);

/**
 * Minimal YAML frontmatter parser tailored to the exact shape used
 * by our methodology .md files:
 *
 *   ---
 *   id: slug
 *   name: Display name
 *   summary: One-line hook.
 *   categories: [technique, repertoire]
 *   templates: [template-id-1, template-id-2]
 *   ---
 *
 * Values are plain strings, arrays are bracketed lists. No nesting,
 * no multiline strings, no quotes.
 */
function parseFrontmatter(source) {
  const match = source.match(/^---\r?\n([\s\S]*?)\r?\n---\r?\n?/);
  if (!match) return { meta: {}, body: source };
  const meta = {};
  for (const line of match[1].split(/\r?\n/)) {
    const kv = line.match(/^([a-zA-Z_][a-zA-Z0-9_]*):\s*(.*)$/);
    if (!kv) continue;
    const key = kv[1];
    let value = kv[2].trim();
    if (value.startsWith("[") && value.endsWith("]")) {
      value = value
        .slice(1, -1)
        .split(",")
        .map((s) => s.trim())
        .filter((s) => s.length > 0);
    }
    meta[key] = value;
  }
  const body = source.slice(match[0].length);
  return { meta, body };
}

const articles = readdirSync(METHODOLOGY_DIR)
  .filter((f) => f.endsWith(".md"))
  .sort()
  .map((f) => {
    const source = readFileSync(join(METHODOLOGY_DIR, f), "utf8");
    const { meta, body } = parseFrontmatter(source);
    return {
      id: meta.id ?? f.replace(/\.md$/, ""),
      name: meta.name ?? f.replace(/\.md$/, ""),
      summary: meta.summary ?? "",
      categories: Array.isArray(meta.categories) ? meta.categories : [],
      templates: Array.isArray(meta.templates) ? meta.templates : [],
      body,
    };
  });

const templates = readdirSync(TEMPLATES_DIR)
  .filter((f) => f.endsWith(".json"))
  .sort()
  .map((f) => {
    const raw = readFileSync(join(TEMPLATES_DIR, f), "utf8");
    return JSON.parse(raw);
  });

const out = `/**
 * methodology-content.generated — DO NOT EDIT BY HAND.
 *
 * Generated by scripts/generate-methodology-content.mjs from the
 * files in src/content/methodology and src/content/templates. Re-run
 * that script whenever the content changes.
 *
 * Slice E.1 (Phase 135).
 */

export type MethodologyArticle = {
  id: string;
  name: string;
  summary: string;
  categories: string[];
  /** Ids into METHODOLOGY_TEMPLATES for the routines this article recommends. */
  templates: string[];
  /** Markdown body (frontmatter stripped). */
  body: string;
};

/**
 * Template routine shape — mirrors the Routine type from routine-types
 * but keeps only the fields templates need. The "Try this template"
 * flow (Slice E.6) hydrates these into full Routine objects when the
 * user commits.
 */
export type MethodologyTemplateItem = {
  id: string;
  type: string;
  category: string;
  label: string;
  estimatedSeconds: number;
  // Type-specific optionals — kept loose here since the template
  // author is expected to match the RoutineItem discriminated union.
  instruction?: string;
  drillId?: string;
  keyDrillId?: string;
  scaleDrillId?: string;
  leadSheetId?: string;
  songId?: string;
  guidanceText?: string;
  bpm?: number;
  beatsPerMeasure?: number;
  beatUnit?: number;
  methodologyId?: string;
};

export type MethodologyTemplate = {
  id: string;
  name: string;
  description: string;
  methodologyId: string;
  estimatedTotalSeconds: number;
  items: MethodologyTemplateItem[];
};

export const METHODOLOGY_ARTICLES: readonly MethodologyArticle[] = ${JSON.stringify(articles, null, 2)} as const;

export const METHODOLOGY_TEMPLATES: readonly MethodologyTemplate[] = ${JSON.stringify(templates, null, 2)} as const;
`;

writeFileSync(OUT_FILE, out, "utf8");
console.log(
  `Wrote ${OUT_FILE}\n  ${articles.length} articles + ${templates.length} templates`,
);
